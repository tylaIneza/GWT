export function getLanguageFromStorage(): Language {
  if (typeof window === 'undefined') return 'en';
  return (localStorage.getItem('ca_lang') as Language) || 'en';
}

export function setLanguageInStorage(lang: Language) {
  if (typeof window !== 'undefined') localStorage.setItem('ca_lang', lang);
}
